// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFile } from 'node:fs/promises';
import { z } from 'zod';
import { ApiClient } from '@/lib/api-client';
import { createAuthApi } from '@/features/auth/api';
import { schoolApi } from '@/features/school/api';
import { createDemoTransport } from '@/mocks/auth';
import { createAuthoringStore } from '@/mocks/authoring-store';
import { authoringApi } from './api';
import { generationInputSchema } from './generation-schemas';

const key = () => crypto.randomUUID();
const metadata = {
  title: 'Algebra',
  instructions: 'Answer all questions.',
  assignmentId: 'demo-math-10a',
  language: 'en' as const,
  durationMinutes: 30,
  passPercent: 50,
  ordering: 'fixed' as const,
};
const specification = {
  revision: 1,
  topics: 'Linear equations',
  guidance: '',
  difficulty: 'mixed' as const,
  mcqCount: 3,
  trueFalseCount: 2,
  marksPerQuestion: 2,
  replaceExisting: false,
};
async function setup() {
  let now = Date.now();
  const store = createAuthoringStore();
  const adminClient = new ApiClient(
    '/api/v1',
    createDemoTransport('school_admin', () => now, store),
  );
  const teacherClient = new ApiClient(
    '/api/v1',
    createDemoTransport('teacher', () => now, store),
  );
  await createAuthApi(adminClient).session();
  await createAuthApi(teacherClient).session();
  const admin = schoolApi(adminClient),
    teacher = authoringApi(teacherClient);
  const draft = await teacher.create(metadata, key());
  return {
    admin,
    teacher,
    teacherClient,
    store,
    draft,
    advance: () => {
      now += 1500;
    },
  };
}
describe('school-controlled AI exam generation', () => {
  it('keeps backend validation generated from the frontend contract source', async () => {
    const source = await readFile('src/features/exams/authoring/generation-schemas.ts', 'utf8');
    const backend = await readFile(
      'nexora-backend/src/modules/authoring/generation-schemas.ts',
      'utf8',
    );
    expect(backend).toBe(
      '// Generated by node scripts/sync-generation-contract.ts. Do not edit.\n' + source,
    );
  });
  it('defaults off, rejects teacher policy changes and supports audited revision-bound admin replay', async () => {
    const c = await setup();
    expect(await c.admin.aiSettings()).toEqual({ aiExamGenerationEnabled: false, revision: 1 });
    await expect(c.teacher.generate(c.draft.examId, specification, key())).rejects.toMatchObject({
      status: 403,
    });
    const body = {
        aiExamGenerationEnabled: true,
        revision: 1,
        reason: 'Enable teacher draft assistance',
      },
      requestKey = key();
    await expect(schoolApi(c.teacherClient).saveAiSettings(body, key())).rejects.toMatchObject({
      status: 403,
    });
    const saved = await c.admin.saveAiSettings(body, requestKey);
    expect(await c.admin.saveAiSettings(body, requestKey)).toEqual(saved);
    await expect(c.admin.saveAiSettings(body, key())).rejects.toMatchObject({ status: 409 });
    expect(c.store.directory.audit.filter((a) => a.action === 'ai_exam_settings')).toHaveLength(1);
    expect(await schoolApi(c.teacherClient).aiSettings()).toEqual(saved);
  });
  it('generates the requested mix and marks, replays once, and requires human review', async () => {
    const c = await setup();
    await c.admin.saveAiSettings(
      { aiExamGenerationEnabled: true, revision: 1, reason: 'Enable' },
      key(),
    );
    const requestKey = key(),
      job = await c.teacher.generate(c.draft.examId, specification, requestKey);
    expect(await c.teacher.generate(c.draft.examId, specification, requestKey)).toEqual(job);
    await expect(
      c.teacher.generate(c.draft.examId, { ...specification, topics: 'Different' }, requestKey),
    ).rejects.toMatchObject({ status: 409 });
    c.advance();
    expect((await c.teacher.job(job.importId)).state).toBe('ready');
    const paper = await c.teacher.items(c.draft.examId);
    expect(paper.items.filter((i) => i.type === 'mcq_single')).toHaveLength(3);
    expect(paper.items.filter((i) => i.type === 'true_false')).toHaveLength(2);
    expect(paper.items.every((i) => i.marks === 2 && !i.reviewed)).toBe(true);
    expect((await c.teacher.get(c.draft.examId)).totalMarks).toBe(10);
    await expect(c.teacher.submit(c.draft.examId, paper.revision, key())).rejects.toMatchObject({
      code: 'AI_REVIEW_REQUIRED',
    });
    await expect(
      c.teacher.generate(c.draft.examId, { ...specification, revision: paper.revision }, key()),
    ).rejects.toMatchObject({ status: 422 });
    const replacement = await c.teacher.generate(
      c.draft.examId,
      { ...specification, revision: paper.revision, replaceExisting: true },
      key(),
    );
    await c.admin.saveAiSettings(
      { aiExamGenerationEnabled: false, revision: 2, reason: 'Disable pending generation' },
      key(),
    );
    expect(await c.teacher.generate(c.draft.examId, specification, requestKey)).toEqual(job);
    await c.admin.saveAiSettings(
      { aiExamGenerationEnabled: true, revision: 3, reason: 'Enable for new requests only' },
      key(),
    );
    c.advance();
    expect((await c.teacher.job(replacement.importId)).state).toBe('failed');
    expect((await c.teacher.items(c.draft.examId)).items).toEqual(paper.items);
  });
  it('submits generated content only after every saved teacher review', async () => {
    const c = await setup();
    await c.admin.saveAiSettings(
      { aiExamGenerationEnabled: true, revision: 1, reason: 'Enable drafting' },
      key(),
    );
    const job = await c.teacher.generate(
      c.draft.examId,
      { ...specification, mcqCount: 1, trueFalseCount: 1 },
      key(),
    );
    c.advance();
    await c.teacher.job(job.importId);
    let paper = await c.teacher.items(c.draft.examId);
    for (const item of paper.items) {
      await c.teacher.saveItem(c.draft.examId, { ...item, reviewed: true }, paper.revision, key());
      paper = await c.teacher.items(c.draft.examId);
    }
    const submitted = await c.teacher.submit(c.draft.examId, paper.revision, key());
    expect(submitted.status).toBe('in_review');
    await expect(
      c.teacher.generate(
        c.draft.examId,
        { ...specification, revision: submitted.revision, replaceExisting: true },
        key(),
      ),
    ).rejects.toMatchObject({ status: 409 });
  });
  it('keeps uploading available while disabled and checks ownership and question limits', async () => {
    const c = await setup();
    expect(
      generationInputSchema.safeParse({ ...specification, mcqCount: 0, trueFalseCount: 0 }).success,
    ).toBe(false);
    expect(
      generationInputSchema.safeParse({ ...specification, mcqCount: 50, trueFalseCount: 1 })
        .success,
    ).toBe(false);
    await expect(c.teacher.generate('foreign-exam', specification, key())).rejects.toMatchObject({
      status: 404,
    });
    const bytes = await readFile('public/templates/nexora-questions.xlsx');
    const job = await c.teacher.upload(
      c.draft.examId,
      1,
      new File([bytes], 'questions.xlsx'),
      key(),
    );
    c.advance();
    expect((await c.teacher.job(job.importId)).state).toBe('ready');
    expect((await c.teacher.items(c.draft.examId)).items).toHaveLength(2);
    for (const role of ['student', 'school_admin'] as const) {
      const client = new ApiClient('/api/v1', createDemoTransport(role, undefined, c.store));
      await createAuthApi(client).session();
      await expect(
        client.request(`/exams/${c.draft.examId}/generate`, z.unknown(), {
          method: 'POST',
          body: specification,
          idempotencyKey: key(),
        }),
      ).rejects.toMatchObject({ status: 403 });
    }
  });
});
